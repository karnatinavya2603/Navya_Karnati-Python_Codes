# LIST
a = [10, 20, 30]
print("List:", a)
print("List Index:", a[0])
print("List Slice:", a[1:3])

print("\n")

# STRING
s = "Navya"
print("String:", s)
print("String Index:", s[0])
print("String Slice:", s[1:4])

print("\n")

# TUPLE
t = (1, 2, 3)
print("Tuple:", t)
print("Tuple Index:", t[1])
print("Tuple Slice:", t[0:2])

print("\n")

# SET
st = {10, 20, 20, 30}
print("Set:", st)

print("\n")

# DICTIONARY
d = {"name": "Navya", "age": 21}
print("Dictionary:", d)
print("Dictionary Value:", d["name"])
